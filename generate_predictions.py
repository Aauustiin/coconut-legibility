import argparse
import json
import re
from vllm import LLM, SamplingParams
from transformers import AutoTokenizer
from utils import get_unique_filepath

RAW_EXPLANATION = "Before submitting an answer, the latent reasoning model generated the following 3 thoughts:\n"
DECODING_EXPLANATION = "Before submitting an answer, the latent reasoning model generated 3 thoughts. Each thought has been decoded into a distribution over tokens:\n"


def parse_args():
    parser = argparse.ArgumentParser(
        description="Load a HuggingFace model and generate predictions using vLLM"
    )
    parser.add_argument(
        "--model-id",
        type=str,
        required=True,
        help="HuggingFace model identifier (e.g., 'Qwen/Qwen3-1.7B')"
    )
    parser.add_argument(
        "--representations-file",
        type=str,
        required=True,
        help="Path to the text representations JSON file generated by generate_representations.py"
    )
    parser.add_argument(
        "--legibility-results",
        type=str,
        default="legibility_results.json",
        help="Path to the legibility results JSON file (default: legibility_results.json)"
    )
    parser.add_argument(
        "--prompt-template",
        type=str,
        default="monitor_prompt.txt",
        help="Path to the prompt template file (default: monitor_prompt.txt)"
    )
    parser.add_argument(
        "--output-file",
        type=str,
        default="monitor_predictions.json",
        help="Filename to save predictions (default: monitor_predictions.json)"
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default="outputs",
        help="Directory to save output files (default: outputs)"
    )
    parser.add_argument(
        "--tensor-parallel-size",
        type=int,
        default=1,
        help="Number of GPUs for tensor parallelism (default: 1)"
    )
    parser.add_argument(
        "--disable-thinking",
        action="store_true",
        help="Disable Qwen3 thinking mode for faster inference"
    )
    parser.add_argument(
        "--cot",
        action="store_true",
        help="Use when predicting correctness on the basis of CoT"
    )
    return parser.parse_args()


def extract_prediction(response: str) -> str:
    """Extract YES/NO prediction from response."""
    pattern = r"<answer>\s*(YES|NO)\s*</answer>"
    matches = re.findall(pattern, response, re.IGNORECASE)
    if matches:
        return matches[-1].upper()
    return "UNKNOWN"


def main():
    args = parse_args()

    print(f"Loading tokenizer: {args.model_id}")
    tokenizer = AutoTokenizer.from_pretrained(args.model_id)

    print(f"Loading vLLM model: {args.model_id}")
    llm = LLM(
        model=args.model_id,
        tensor_parallel_size=args.tensor_parallel_size,
        trust_remote_code=True,
        seed=42,
        max_model_len=8192,
        gpu_memory_utilization=0.9,
    )

    print(f"Loading legibility results from: {args.legibility_results}")
    with open(args.legibility_results, "r") as f:
        legibility_results = json.load(f)

    print(f"Loading prompt template from: {args.prompt_template}")
    with open(args.prompt_template, "r") as f:
        prompt_template = f.read()

    if not args.cot:
        print(f"Loading text representations from: {args.representations_file}")
        with open(args.representations_file, "r") as f:
            representations_data = json.load(f)
            text_representations = representations_data["representations"]
            thought_type = representations_data.get('thought_type', 'unknown')
            print(f"  Thought type: {thought_type}")
        if thought_type == "raw":
            explanation = RAW_EXPLANATION
        else:
            explanation = DECODING_EXPLANATION

    print(f"\n{'='*80}")
    print(f"Preparing {len(legibility_results)} prompts...")
    print(f"{'='*80}\n")

    all_prompts = []
    for i, result in enumerate(legibility_results):

        if args.cot:
            prompt_content = prompt_template.format(
                question=result["question"],
                ground_truth=result["ground_truth_answer"],
                reasoning=result["model_reasoning"]
            )
        else:
            prompt_content = prompt_template.format(
                question=result["question"],
                ground_truth=result["ground_truth_answer"],
                reasoning=result["model_reasoning"],
                representation = explanation + text_representations[i]
            )

        # Optionally disable thinking mode for Qwen3
        if args.disable_thinking:
            prompt_content += "\n/no_think"

        messages = [{"role": "user", "content": prompt_content}]
        formatted_prompt = tokenizer.apply_chat_template(
            messages,
            tokenize=False,
            add_generation_prompt=True
        )
        all_prompts.append(formatted_prompt)

    sampling_params = SamplingParams(
        max_tokens=4096,
        temperature=0.6,
        top_p=0.95,
        seed=42,
    )

    # Generate all responses in one batched call
    print(f"Generating predictions for {len(all_prompts)} questions...")
    outputs = llm.generate(all_prompts, sampling_params)

    print(f"\n{'='*80}")
    print("Processing results...")
    print(f"{'='*80}\n")

    predictions = []

    for i, output in enumerate(outputs):
        response = output.outputs[0].text
        prediction = extract_prediction(response)
        actual_correct = legibility_results[i]["is_correct"]

        predictions.append({
            "question_idx": i,
            "prediction": prediction,
            "full_response": response.strip(),
            "actual_correct": actual_correct
        })

    # Save with unique filename
    output_path = get_unique_filepath(args.output_dir, args.output_file)
    with open(output_path, "w") as f:
        json.dump(predictions, f, indent=2)

    print(f"\n{'='*80}")
    print("SUMMARY")
    print(f"{'='*80}")
    print(f"Total questions: {len(predictions)}")
    print(f"\nPredictions saved to: {output_path}")
    print(f"{'='*80}")


if __name__ == "__main__":
    main()